def pair(f, k0, k1):
    """Fit f[k+1] = A f[k] + B f[k-1] (a conjugate pair of simple singularities) over k0 <= k < k1;
    returns the singularity z with Im z < 0, relative to the expansion point."""
    m = [[mpfr(0)] * 3 for _ in range(2)]
    for k in range(k0, k1):
        s = abs(f[k])
        x, y, t = f[k] / s, f[k - 1] / s, f[k + 1] / s
        m[0][0] += x * x; m[0][1] += x * y; m[1][1] += y * y; m[0][2] += x * t; m[1][2] += y * t
    det = m[0][0] * m[1][1] - m[0][1] ** 2
    A, B = (m[0][2] * m[1][1] - m[0][1] * m[1][2]) / det, (m[0][0] * m[1][2] - m[0][1] * m[0][2]) / det
    w = (float(A) + cmath.sqrt(float(A * A + 4 * B))) / 2
    z = 1 / w
    return z if z.imag < 0 else z.conjugate()


