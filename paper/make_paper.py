def per_electron(run):
    """rho(0) and <r^k> per electron (the mean over orbitals, each doubly occupied) as plain decimal strings."""
    p = run["props"]
    return {"rho0": format(D(p["rho0"]), "f")} | {k: format(sum(map(D, p["rk"][str(k)])) / len(p["rk"][str(k)]), "f") for k in KS}


def vr_sf(run):
    """Significant figures of the virial ratio V/T = -2: |V/T + 2| / 2 = |1 + E/T| / 2, with T = sum_i 2 T_i from
    each orbital normalised on its own (the P = S^-1 kinetic energy is good only to ~S_12, like any property)."""
    T = 2 * sum(map(D, run["props"]["T"]))
    return float(-(abs(1 + D(run["E"]) / T) / 2).log10())


def sig(s, n):
    """Decimal string truncated to n significant figures, grouped in fives after the point."""
    i, f = s.split(".")
    lead = len(i.lstrip("0"))
    return grouped(s, n - lead if lead else n + len(f) - len(f.lstrip("0")))


