def bisect(g, lo, hi):
    for _ in range(200):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if g(mid) > 0 else (lo, mid)
    return lo


def zeta_opt(N):
    return bisect(lambda z: N * math.log((z + kappa) / (z - kappa)) - 2 * tau * math.sqrt(2 * z * N), kappa * 1.000001, 1e4)


def model_digits(N):
    z = zeta_opt(N)
    return 2 * N * math.log((z + kappa) / (z - kappa)) / LN10


