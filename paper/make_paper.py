def common(a, b):
    """Leading significant digits shared by two decimal strings."""
    a, b = a.lstrip("-0.").replace(".", ""), b.lstrip("-0.").replace(".", "")
    return next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))


def split(s, decimals, per_line=21):
    """Digits for a revtex split environment: groups of three, `per_line` decimals per line."""
    sign, (i, f) = ("-" if s[0] == "-" else ""), s.lstrip("-").split(".")
    f = f[:decimals]
    g = lambda l: r"\,".join(l[j:j + 3] for j in range(0, len(l), 3))  # noqa: E731
    lines = [g(f[k:k + per_line]) for k in range(0, len(f), per_line)]
    return (r"\mathord{-}" if sign else "") + i + "." + (r"\\ &\hphantom{-" + i + ".}").join(lines)


def sci(x, p=1):
    """Decimal -> TeX a\\times10^{b} (floats underflow below 1e-308)."""
    m, e = f"{D(x):.{p}e}".split("e")
    return rf"{m}\times10^{{{int(e)}}}"


def dy(pair):
    return mpfr(mpz(pair[0])) * mpfr(2) ** int(pair[1])


def grouped(s, decimals, per=5):
    """'-2.86167999...' -> texttt with thin spaces every `per` decimals, cut to `decimals`."""
    sign, (i, f) = ("$-$" if s[0] == "-" else ""), s.lstrip("-").split(".")
    f = f[:decimals]
    return sign + i + "." + r"\,".join(f[k:k + per] for k in range(0, len(f), per))


